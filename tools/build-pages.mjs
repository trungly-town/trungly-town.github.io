#!/usr/bin/env node
/*
 * Builds the shareable pages that link previews (LinkedIn, Facebook, X, Zalo, Slack…) read.
 * Those crawlers don't run JavaScript, so each post and project gets a real HTML page with its own
 * title, description and image:
 *
 *   blog/<slug>/index.html       one page per published post
 *   projects/<id>/index.html     one page per project
 *   assets/og/*.jpg              1200×630 preview images, drawn from tools/og/card.html (needs Google Chrome)
 *   assets/js/static-pages.js    tells the site which pages exist, so links point to them
 *
 * Run it after adding or editing a post or a project:
 *   node tools/build-pages.mjs               pages + images
 *   node tools/build-pages.mjs --no-images   pages only (fast)
 *   node tools/build-pages.mjs --drafts      also build draft posts, to preview their card locally
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://trungly-town.github.io';
const MARK = '<!-- generated by tools/build-pages.mjs from post.html / project.html: edit those, then rebuild -->';
const args = new Set(process.argv.slice(2));
const CHROME = process.env.CHROME || [
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/Applications/Chromium.app/Contents/MacOS/Chromium',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].find((p) => fs.existsSync(p));

const file = (rel) => path.join(ROOT, rel);
const read = (rel) => fs.readFileSync(file(rel), 'utf8');
const write = (rel, text) => {
  fs.mkdirSync(path.dirname(file(rel)), { recursive: true });
  fs.writeFileSync(file(rel), text);
};
const attr = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// the data files are plain browser scripts that assign to window.*
const load = (rel, key) => {
  const window = {};
  vm.runInNewContext(read(rel), { window });
  return window[key] || [];
};
const posts = load('posts/posts.js', 'POSTS').filter((p) => args.has('--drafts') || !p.draft);
const projects = load('assets/js/projects-data.js', 'PROJECTS');

/* ---------- HTML helpers ---------- */
// pages live two folders down, so every relative link gets "../../"
const rebase = (html, prefix) => html.replace(/(\s(?:href|src))="(?![#/]|[a-z][a-z0-9+.-]*:)([^"]*)"/gi, `$1="${prefix}$2"`);

// replace a <meta>/<link> tag, or add it after the theme-color tag
const upsert = (html, tag, re) => (re.test(html)
  ? html.replace(re, tag)
  : html.replace(/(<meta name="theme-color"[^>]*>)/, `$1\n  ${tag}`));
const meta = (html, kind, key, value) => upsert(html,
  `<meta ${kind}="${key}" content="${attr(value)}">`,
  new RegExp(`<meta ${kind}="${key.replace(/[.:]/g, '\\$&')}" content="[^"]*">`));

const page = (template, { title, ogTitle, description, url, image, alt, root, bodyData, extraMeta = [] }) => {
  let html = rebase(read(template), root);
  html = html.replace('<!doctype html>', `<!doctype html>\n${MARK}`);
  html = html.replace('<html lang="en">', `<html lang="en" data-root="${root}">`);
  html = html.replace(/<body class="([^"]*)">/, `<body class="$1" ${bodyData}>`);
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${attr(title)}</title>`);
  html = meta(html, 'name', 'description', description);
  html = upsert(html, `<link rel="canonical" href="${url}">`, /<link rel="canonical" href="[^"]*">/);
  html = meta(html, 'property', 'og:title', ogTitle);
  html = meta(html, 'property', 'og:description', description);
  html = meta(html, 'property', 'og:url', url);
  html = meta(html, 'property', 'og:image', image);
  html = meta(html, 'property', 'og:image:alt', alt);
  extraMeta.forEach(([kind, key, value]) => { html = meta(html, kind, key, value); });
  return html;
};

/* ---------- Preview images ---------- */
const shots = [];
const image = (name, params) => {
  shots.push([name, params]);
  return `${SITE}/assets/og/${name}.jpg`;
};
const chip = (value, label) => `**${value}** ${label}`;

/* ---------- Build ---------- */
const built = { posts: [], projects: [] };

image('home', {
  kind: 'home',
  kicker: 'Portfolio',
  sub: 'Senior Data Scientist (AI) · Manulife',
  chips: [chip('$15M+', 'value delivered with AI'), chip('2,000+', 'agents on M-Smart'), chip('2×', 'Databricks certified')].join('|'),
});
image('blog', {
  kind: 'blog',
  kicker: 'Blog',
  title: 'Notes on GenAI, causal inference & shipping data products',
  sub: 'Practical write-ups from building Agentic RAG assistants and measuring what AI is really worth.',
  chips: [...new Set(posts.flatMap((p) => p.tags || []))].slice(0, 4).join('|'),
});

posts.forEach((p) => {
  const url = `${SITE}/blog/${p.slug}/`;
  write(`blog/${p.slug}/index.html`, page('post.html', {
    title: `${p.title} — Ly Minh Trung (Philip)`,
    ogTitle: p.title,
    description: p.summary,
    url,
    alt: p.title,
    root: '../../',
    bodyData: `data-slug="${attr(p.slug)}"`,
    image: image(`post-${p.slug}`, {
      kind: 'post',
      kicker: ['Blog', (p.tags || [])[0]].filter(Boolean).join(' · '),
      title: p.title,
      sub: p.summary,
      chips: (p.tags || []).slice(0, 3).join('|'),
    }),
    extraMeta: [['property', 'article:published_time', p.date]],
  }));
  built.posts.push(p.slug);
});

projects.forEach((p) => {
  const url = `${SITE}/projects/${p.id}/`;
  write(`projects/${p.id}/index.html`, page('project.html', {
    title: `${p.title} — Ly Minh Trung (Philip)`,
    ogTitle: p.title,
    description: p.summary,
    url,
    alt: p.title,
    root: '../../',
    bodyData: `data-id="${attr(p.id)}"`,
    image: image(`project-${p.id}`, {
      kind: 'project',
      kicker: `Project · ${p.org}`,
      title: p.title,
      sub: p.kicker,
      chips: (p.metrics ? p.metrics.map((m) => chip(m.value, m.label)) : (p.stack || []).slice(0, 3)).join('|'),
    }),
  }));
  built.projects.push(p.id);
});

write('assets/js/static-pages.js', `// generated by tools/build-pages.mjs — the shareable pages that exist, so links can point to them
window.STATIC_PAGES = ${JSON.stringify(built, null, 2)};
`);

/* ---------- Remove pages and images of deleted (or unpublished) entries ---------- */
const stale = [];
[['blog', built.posts], ['projects', built.projects]].forEach(([dir, keep]) => {
  if (!fs.existsSync(file(dir))) return;
  fs.readdirSync(file(dir)).forEach((name) => {
    const index = file(`${dir}/${name}/index.html`);
    if (keep.includes(name) || !fs.existsSync(index) || !fs.readFileSync(index, 'utf8').includes(MARK)) return;
    fs.rmSync(file(`${dir}/${name}`), { recursive: true });
    stale.push(`${dir}/${name}/`);
  });
});
if (fs.existsSync(file('assets/og'))) {
  const wanted = new Set(shots.map(([name]) => `${name}.jpg`));
  fs.readdirSync(file('assets/og'))
    .filter((f) => /^(post|project)-.+\.jpg$/.test(f) && !wanted.has(f))
    .forEach((f) => { fs.rmSync(file(`assets/og/${f}`)); stale.push(`assets/og/${f}`); });
}

/* ---------- Draw the images ---------- */
let drawn = 0;
if (args.has('--no-images')) {
  console.log('Skipped images (--no-images).');
} else if (!CHROME) {
  console.warn('Google Chrome not found — skipped images. Set CHROME=/path/to/chrome to draw them.');
} else {
  fs.mkdirSync(file('assets/og'), { recursive: true });
  const card = pathToFileURL(file('tools/og/card.html')).href;
  shots.forEach(([name, params]) => {
    execFileSync(CHROME, [
      '--headless=new', '--disable-gpu', '--hide-scrollbars',
      '--window-size=1200,630', '--virtual-time-budget=5000',
      `--screenshot=${file(`assets/og/${name}.jpg`)}`,
      `${card}?${new URLSearchParams(params)}`,
    ], { stdio: 'ignore' });
    drawn += 1;
  });
}

console.log(`Built ${built.posts.length} post page(s), ${built.projects.length} project page(s), ${drawn} image(s).`);
if (stale.length) console.log(`Removed: ${stale.join(', ')}`);
